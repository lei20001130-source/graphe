
public class PairIntFloat {

	private int a;
	private float b;
	
	public PairIntFloat(int a, float b) {
		this.a=a;
		this.b=b;
	}
	
	public int getA() {
		return this.a;
	}
	
	public float getB() {
		return this.b;
	}
	
	public void setA(int x) {
		this.a=x;
	}
	
	public void setB(float y) {
		this.b=y;
	}
}
